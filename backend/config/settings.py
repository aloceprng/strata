def env_flag(name: str, default: bool) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() not in ('0', 'false', 'no', 'off', '')


DEBUG = env_flag('DJANGO_DEBUG', True)

# No key literal lives in this repository. Set DJANGO_SECRET_KEY in .env for a
# stable local key; without one, development gets a throwaway key that changes
# on every restart, which logs you out and is meant to be mildly annoying.
# With DEBUG off there is no fallback at all — a generated key would silently
# invalidate every session on each deploy.
SECRET_KEY = os.environ.get('DJANGO_SECRET_KEY')
if not SECRET_KEY:
    if not DEBUG:
        raise ImproperlyConfigured(
            'DJANGO_SECRET_KEY must be set when DEBUG is off. '
            'Generate one with: python -c '
            '"from django.core.management.utils import get_random_secret_key as k; print(k())"'
        )
    SECRET_KEY = get_random_secret_key()

